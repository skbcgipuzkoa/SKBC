import assert from "node:assert/strict";
import { isBirthdayToday } from "../src/lib/birthday.ts";
const at = (value) => new Date(value);
assert.equal(isBirthdayToday("2000-11-05", at("2026-11-04T23:30:00Z")), true);
assert.equal(isBirthdayToday("2000-11-04", at("2026-11-04T23:30:00Z")), false);
assert.equal(isBirthdayToday("2000-07-05", at("2026-07-04T22:30:00Z")), true);
assert.equal(isBirthdayToday("2000-02-29", at("2028-02-29T12:00:00Z")), true);
for (const day of ["2027-02-28", "2027-03-01"]) assert.equal(isBirthdayToday("2000-02-29", at(`${day}T12:00:00Z`)), false);
for (const value of [null, "", "2001-02-29", "2000-04-31", "0000-11-05", "2000-1-05", "2000-11-05T00:00:00Z", "2027-11-05", "garbage"]) assert.equal(isBirthdayToday(value, at("2026-11-05T12:00:00Z")), false, String(value));
assert.equal(isBirthdayToday("2000-11-05", new Date("invalid")), false);
console.log("Birthday date checks passed");
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import ts from "typescript";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
const require = createRequire(import.meta.url);
function loadTs(relative, overrides = {}) {
  const source = readFileSync(new URL(relative, import.meta.url), "utf8");
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
  const module = { exports: {} };
  new Function("require", "module", "exports", code)((id) => overrides[id] ?? require(id), module, module.exports);
  return module.exports;
}
const { BirthdayRibbon } = loadTs("../src/components/birthday-ribbon.tsx");
const { BirthdayCelebration } = loadTs("../src/components/birthday-celebration.tsx", { "@/lib/birthday": { isBirthdayToday }, "./birthday-ribbon": { BirthdayRibbon } });
const render = (props) => renderToStaticMarkup(React.createElement(BirthdayCelebration, { birthDate: "2000-11-05", name: "Prueba", active: true, now: at("2026-11-05T12:00:00Z"), ...props }));
assert.match(render(), /ZORIONAK!!!/);
assert.match(render(), /Prueba, ¡feliz cumpleaños!/);
assert.match(render(), /Pausar animación/);
assert.match(render(), /class="birthday-confetti" aria-hidden="true"/);
assert.doesNotMatch(render(), /2000-11-05/);
assert.equal(render({ active: false }), "");
assert.equal(render({ birthDate: "2000-11-06" }), "");
assert.equal(render({ birthDate: null }), "");
const css = readFileSync(new URL("../src/app/globals.css", import.meta.url), "utf8");
assert.match(css, /@media \(prefers-reduced-motion: reduce\) \{ \.birthday-celebration/);
assert.match(css, /\.birthday-celebration \.birthday-confetti, \.birthday-celebration \.birthday-motion-toggle \{ display: none; \}/);
assert.match(css, /animation: birthday-fall 2\.6s ease-in var\(--delay\) 1 both/);
console.log("Birthday real component render checks passed");
