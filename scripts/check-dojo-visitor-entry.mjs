import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const visitors=read('src/app/portal/[dojo]/clases/[id]/visitantes/page.tsx');
assert(visitors.includes('`/dojo/${session.legacy_id}`'));
assert(!visitors.includes('`/dojo/${session.legacy_id}?step=techniques`'),'Visitors must not force adult techniques');
const source=read('src/app/dojo/[legacyId]/page.tsx');
const ast=ts.createSourceFile('page.tsx',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
const fn=ast.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text==='resolveStep');
assert(fn);
const code=ts.transpileModule(fn.getText(ast),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const context=vm.createContext({});vm.runInContext(code+';this.resolve=resolveStep;',context);
const initial={hasKids:true,kidsClosed:false,adultClosed:false,kidsAttendance:0,adultAttendance:0,completedPlan:0};
assert.equal(context.resolve(undefined,initial),'kids');
assert.equal(context.resolve(undefined,{...initial,hasKids:false}),'techniques');
assert.equal(context.resolve(undefined,{...initial,kidsClosed:true}),'techniques');
assert.equal(context.resolve(undefined,{...initial,kidsAttendance:12}),'techniques');
assert.equal(context.resolve('kids',{...initial,kidsAttendance:12}),'kids');
assert.equal(context.resolve(undefined,{...initial,kidsAttendance:12,completedPlan:4}),'adults');
assert.equal(context.resolve(undefined,{...initial,kidsAttendance:12,completedPlan:4,adultAttendance:10}),'close');
assert.equal(context.resolve(undefined,{...initial,kidsClosed:true,adultClosed:true}),'done');
console.log('PASS: visitor entry starts with children and Dojo resumes through adult plan, attendance and closure');
